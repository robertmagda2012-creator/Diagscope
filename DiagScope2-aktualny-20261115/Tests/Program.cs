using DiagScope2;
using System.Text.Json;
void Check(bool yes,string name){if(!yes)throw new Exception("FAIL "+name);Console.WriteLine("PASS "+name);}
var real=Importer.Read(Path.Combine(AppContext.BaseDirectory,"fixtures","real-vcds.csv"));
Check(real.Channels.Count==10,"real VCDS: ten nonempty channels");
Check(real.Channels.Select(c=>c.Clock).Distinct().Count()==3,"real VCDS: three independent clocks");
Check(real.Channels.Where(c=>c.Name.Contains("Bin.")).All(c=>c.TextState),"binary states remain text");
Check(real.Channels[0].Samples.First().Time==.27,"first group original time");
Check(real.Channels.Last().Samples.First().Time==.02,"third group original time");
Check(real.Channels[0].Samples.First().Value==760,"real RPM");
Console.WriteLine($"Real file: {real.Rows} rows, {real.Channels.Sum(c=>c.Samples.Count)} channel samples");
Check(Importer.Csv("t;v\n0;\"Gaz; test\"\n1;\"cytat \"\"x\"\"\"",';')[2][1]=="cytat \"x\"","quoted CSV");
Check(Importer.Time("01:02:03,5")==3723.5,"decimal clock");
Check(Importer.Number("")==null,"blank is not zero");
var c=new Channel{Samples=new[]{("0","1"),("1","2"),("2",""),("10","4"),("10","5"),("9","6"),("bad","7")}.Select((p,i)=>new PointSample{Time=Importer.Time(p.Item1),Value=Importer.Number(p.Item2),Raw=p.Item2,Row=i+1}).ToList()};
var q=Analyzer.Analyze(c);
Check(q.Gaps.Count==1&&q.Gaps[0].Duration==8,"gap and duration");
Check(q.InvalidTime==1&&q.Duplicate==1&&q.Reverse==1&&q.Missing==1,"invalid, duplicate, reversed time and missing value");
var js=Importer.JsonLines("{\"type\":\"frame\",\"samples\":[{\"id\":\"rpm\",\"name\":\"RPM\",\"time\":0.5,\"value\":800,\"unit\":\"rpm\"},{\"id\":\"s\",\"name\":\"Stan\",\"time\":0.7,\"raw\":\"Gaz\",\"unit\":\"stan\"}]}\nnot-json");
Check(js.Channels.Count==2&&js.Channels[1].TextState&&js.Warnings.Count==1,"JSONL states, independent times and malformed row");
var study=new Study{Logs=[real,js],Vehicle=new(){Vin="WAUZZZ4BZWN123456"}};
study.Logs[0].Markers.Add(new(){Time=4.2,Source="test",Uncertainty=.3});
var path=Path.Combine(Path.GetTempPath(),"DiagScope-tests-"+Guid.NewGuid()+".json");
Store.WriteAtomic(path,JsonSerializer.Serialize(study,Store.Options));
var loaded=Store.Load(path);
Check(loaded.Logs[0].Markers[0].Time==4.2&&loaded.Logs[0].Channels[0].Samples.Count==real.Channels[0].Samples.Count,"save/load full session");
Store.WriteAtomic(path,JsonSerializer.Serialize(study,Store.Options));
Check(File.Exists(path+".bak"),"previous version backup");
File.Delete(path);File.Delete(path+".bak");
Console.WriteLine("ALL TESTS PASSED");
Extended.Run();